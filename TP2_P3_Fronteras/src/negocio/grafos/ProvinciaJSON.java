package negocio.grafos;

public class ProvinciaJSON {
    private int id;
    private String nombre;
    private double lat;
    private double lon;

    public int getId() {
        return id;
    }

    public String getNombre() {
        return nombre;
    }

    public double getLat() {
        return lat;
    }

    public double getLon() {
        return lon;
    }
}